package com.springboot.web.wikipulseproject.yt_repo;

import com.springboot.web.wikipulseproject.model.EnrichedEvent;

import java.util.List;
import java.util.Map;

/**
 * Окно свежих правок в памяти. Стык между поллером и живой картой.
 * <p>
 * Полное описание договорённости — docs/03-contracts/backend-cache.md.
 *
 * <h2>Что гарантирует реализация</h2>
 * <ul>
 *   <li>ключ — H3-индекс уровня 9, как пришёл из очереди;</li>
 *   <li>событий старше 30 минут в кэше нет;</li>
 *   <li>дублей по {@code eventId} нет;</li>
 *   <li>возвращаемые коллекции иммутабельны, обход безопасен во время записи;</li>
 *   <li>ячейка без событий из снимка исчезает;</li>
 *   <li>события внутри ячейки идут от новых к старым.</li>
 * </ul>
 *
 * <h2>На что может рассчитывать читатель</h2>
 * Не фильтровать по времени, не дедуплицировать, не копировать защитно,
 * не проверять на {@code null} и на пустые списки.
 * <p>
 * География, bbox и резолюции реализации не касаются: она знает только
 * ключ уровня 9.
 */
public interface RecentEventsCache {

    /**
     * Кладёт событие в ячейку {@code event.h3_r9()}.
     * Вызывает только поллер. Повторный вызов с тем же {@code eventId}
     * не создаёт дубля.
     */
    void put(EnrichedEvent event);

    /**
     * Снимок на момент вызова: ключ — H3-индекс уровня 9,
     * значение — события ячейки от новых к старым.
     * <p>
     * Снимок, а не чтение по ключам: карта сворачивает ключи вверх до нужной
     * резолюции, поэтому нужен обход всех ячеек. Разворот запроса вниз до r9
     * неприменим — от r3 до r9 около 117 тысяч дочерних ячеек на одну.
     *
     * @return пустая мапа, если событий нет; никогда не {@code null}
     */
    Map<String, List<EnrichedEvent>> snapshot();
}
