package tech.wikipulse.backend.repository;

import tech.wikipulse.backend.model.EnrichedEvent;

import java.util.List;
import java.util.Map;

/**
 * Стык двух половин бэкенда: поллер наполняет кэш из очереди, сервис карты
 * читает его и отдаёт наружу. Договорённость меняется с согласия обеих сторон.
 *
 * <p>Запись гарантирует, а чтение вправе на это рассчитывать: ключ — H3-индекс
 * девятого уровня; правок старше окна и дублей по {@code event_id} в кэше нет;
 * событий без {@code event_ts} и «из будущего» нет; коллекции иммутабельны;
 * пустая ячейка в снимок не попадает; пустой кэш — пустая мапа.
 *
 * <p>География, bbox и резолюции — не зона записи. Структура хранения,
 * вытеснение и выбор библиотеки — не зона чтения.
 */
public interface RecentEventsCache {

    void put(EnrichedEvent event);

    /**
     * Срез на момент вызова: ключ — {@code h3_r9}, значение — события ячейки,
     * отсортированные по {@code event_ts}, новые первыми.
     *
     * <p>Чтение снимком, а не по ключам: карта сворачивает ключи кэша вверх
     * до нужной резолюции, поэтому ей нужен обход всех ячеек.
     */
    Map<String, List<EnrichedEvent>> snapshot();
}
